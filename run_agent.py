from agent.orchestrator import graph

def main():
    print("Initializing AI Multi-Omics Agent...")
    
    # 1. Define the user's goal and the dataset to use
    initial_state = {
        "goal": "Identify key oncogenic driver genes in breast cancer through integrated mutation and expression analysis",
        "cancer_type": "BRCA",
        "plan": [],
        "plan_valid": False,
        "retry_count": 0
    }

    print(f"\nGoal: {initial_state['goal']}")
    print(f"Cancer Type: {initial_state['cancer_type']}\n")
    print("Agent is thinking and executing pipeline steps...\n")

    # 2. Run the LangGraph workflow
    try:
        # stream() lets us see each node as it executes
        final_state = None
        for output in graph.stream(initial_state):
            for key, value in output.items():
                final_state = value # Keep track of the latest state
                
                # If the planner just finished, beautifully print the plan it created
                if key == "planner_node":
                    plan = value.get("plan", [])
                    print("\n" + "="*50)
                    print("🤖 THE PLANNER AGENT HAS CREATED A PLAN!")
                    print("="*50)
                    print("To achieve your goal, the AI has decided to run these specific tools in this exact order:")
                    for i, step in enumerate(plan, 1):
                        print(f"  {i}. {step}")
                    print("="*50 + "\n")
                
        # 3. Print the final report generated by the LLM
        print("\n" + "*"*60)
        print("🔬 FINAL BIOLOGICAL REPORT GENERATED BY AI 🔬")
        print("*"*60 + "\n")
        print(final_state.get("report", "No report generated."))
        print("\n" + "*"*60)
        print("Check the 'data/processed/' folder for your generated charts!")
        
    except Exception as e:
        print(f"\nAn error occurred: {e}")
        print("Make sure Ollama is running in the background!")

if __name__ == "__main__":
    main()
